def _create_verified_customer(name: str, credit_limit: float = 5000.0) -> dict:
    """Helper to create a customer with verified phone."""
    phone = f"98{int(datetime.utcnow().timestamp() * 1000) % 100000000:08d}"
    res = client.post("/api/v1/customers", json={
        "full_name": name,
        "phone": phone,
        "credit_limit": credit_limit,
        "is_phone_verified": True,
        **DEFAULT_ADDR
    })
    assert res.status_code == 201, f"Failed to create customer: {res.text}"
    return res.json()


def _get_or_create_product(name: str = "Aashirvaad Atta", price: float = 45.0, stock: float = 100.0) -> Product:
    db = SessionLocal()
    try:
        prod = db.query(Product).filter(Product.name == name).first()
        if not prod:
            prod = Product(
                name=name,
                category="Grains & Staples",
                unit="kg",
                unit_price=price,
                stock_quantity=stock,
                min_stock_threshold=10.0,
                is_active=True
            )
            db.add(prod)
            db.commit()
            db.refresh(prod)
        elif prod.stock_quantity < 10.0:
            prod.stock_quantity = stock
            db.commit()
            db.refresh(prod)
        return prod
    finally:
        db.close()


def test_01_to_05_udhaar_customer_list_sorting_and_search():
    """Points 1-5: Udhaar customer list loads, sorts alphabetically, case-insensitive search, and handles empty/no-results."""
    # Create customers with specific alphabetical order: "Aarav", "Bhavna", "Chirag"
    c_b = _create_verified_customer("Bhavna Patel")
    c_a = _create_verified_customer("Aarav Sharma")
    c_c = _create_verified_customer("Chirag Gupta")

    # Point 1: List loads
    res = client.get("/api/v1/customers")
    assert res.status_code == 200
    custs = res.json()
    assert len(custs) >= 3

    # Point 2: Sorts alphabetically (case-insensitive deterministic sorting)
    names = [c["full_name"] for c in custs]
    sorted_names = sorted(names, key=lambda s: s.lower())
    assert names == sorted_names, "Customers must be deterministically sorted alphabetically"

    # Point 3 & 4: Search works and is case-insensitive
    search_res = client.get("/api/v1/customers?query=aarav")
    assert search_res.status_code == 200
    search_data = search_res.json()
    assert any(c["id"] == c_a["id"] for c in search_data)
    assert not any(c["id"] == c_b["id"] for c in search_data)

    search_upper = client.get("/api/v1/customers?query=BHAVNA")
    assert search_upper.status_code == 200
    assert any(c["id"] == c_b["id"] for c in search_upper.json())

    # Point 5: Search with no results behaves gracefully
    no_res = client.get("/api/v1/customers?query=NonExistentCustomerNameXYZ999")
    assert no_res.status_code == 200
    assert no_res.json() == []


