def test_09_to_13_otp_generation_sms_and_whatsapp():
    """Points 9-13: SMS and WhatsApp create 4-digit OTP session generated strictly server-side."""
    cust = _create_verified_customer("Esha Deol", credit_limit=3000.0)
    prod = _get_or_create_product()

    # Create bill
    bill_res = client.post("/api/v1/billing/finalize", json={
        "customer_id": cust["id"],
        "items": [{"product_id": prod.id, "quantity": 1.0}],
        "payment_mode": "UDHAAR"
    })
    bill_id = bill_res.json()["id"]

    # Point 9: SMS delivery session
    sms_res = client.post("/api/v1/verification/sessions", json={
        "bill_id": bill_id,
        "delivery_channel": "SMS"
    })
    assert sms_res.status_code == 201
    sms_data = sms_res.json()
    assert sms_data["delivery_channel"] == "SMS"
    assert sms_data["verification_type"] == "OTP"
    assert sms_data["otp_length"] == 4
    assert "SMS Verification (Simulated/Mock Delivery" in sms_data["channel_status_note"]
    assert "[SIMULATED SMS DELIVERY]" in sms_data["delivery_message_preview"]

    # Point 10: WhatsApp delivery session
    wa_res = client.post("/api/v1/verification/sessions", json={
        "bill_id": bill_id,
        "delivery_channel": "WHATSAPP"
    })
    assert wa_res.status_code == 201
    wa_data = wa_res.json()
    assert wa_data["delivery_channel"] == "WHATSAPP"
    assert wa_data["verification_type"] == "OTP"
    assert "[SIMULATED WHATSAPP DELIVERY]" in wa_data["delivery_message_preview"]

    # Point 11: OTP is exactly 4 digits
    db = SessionLocal()
    try:
        vs = db.query(VerificationSession).filter(VerificationSession.bill_id == bill_id).first()
        assert vs.otp_code is not None
        assert len(vs.otp_code) == 4
        assert vs.otp_code.isdigit()
        assert 0 <= vs.target_number <= 9999

        # Point 12: OTP is generated server-side (stored in DB)
        assert vs.otp_code == f"{vs.target_number:04d}"
    finally:
        db.close()

    # Point 13: OTP cannot be generated by frontend input
    fake_res = client.post("/api/v1/verification/sessions", json={
        "bill_id": bill_id,
        "delivery_channel": "SMS",
        "otp": "0000"
    })
    assert fake_res.status_code == 201
    db = SessionLocal()
    try:
        vs = db.query(VerificationSession).filter(VerificationSession.bill_id == bill_id).first()
        assert vs.otp_code is not None
    finally:
        db.close()


def test_14_to_17_otp_verification_success_failure_expired_and_single_use():
    """Points 14-17: Correct OTP succeeds, incorrect OTP fails, expired OTP fails, already-used OTP fails."""
    cust = _create_verified_customer("Gaurav Kapoor", credit_limit=5000.0)
    prod = _get_or_create_product("Premium Basmati Rice", price=90.0, stock=50.0)

    bill_res = client.post("/api/v1/billing/finalize", json={
        "customer_id": cust["id"],
        "items": [{"product_id": prod.id, "quantity": 2.0}],
        "payment_mode": "UDHAAR"
    })
    bill_id = bill_res.json()["id"]

    sess_res = client.post("/api/v1/verification/sessions", json={"bill_id": bill_id})
    s_data = sess_res.json()
    session_id = s_data["session_id"]

    db = SessionLocal()
    try:
        vs = db.query(VerificationSession).filter(VerificationSession.id == session_id).first()
        correct_otp = vs.otp_code
    finally:
        db.close()

    # Point 15: Incorrect OTP fails
    wrong_otp = "0000" if correct_otp != "0000" else "9999"
    fail_res = client.post("/api/v1/verification/verify", json={
        "session_id": session_id,
        "otp": wrong_otp
    })
    assert fail_res.status_code == 200
    assert fail_res.json()["success"] is False
    assert fail_res.json()["status"] == "FAILED"

    # Point 14: Correct OTP succeeds
    success_res = client.post("/api/v1/verification/verify", json={
        "session_id": session_id,
        "otp": correct_otp
    })
    assert success_res.status_code == 200
    assert success_res.json()["success"] is True
    assert success_res.json()["status"] == "VERIFIED"

    # Point 17: Already-used OTP/session fails on second attempt (single-use enforcement)
    reused_res = client.post("/api/v1/verification/verify", json={
        "session_id": session_id,
        "otp": correct_otp
    })
    assert reused_res.status_code == 400
    assert "already been completed" in reused_res.json()["detail"].lower()

    # Point 16: Expired OTP fails
    bill_res2 = client.post("/api/v1/billing/finalize", json={
        "customer_id": cust["id"],
        "items": [{"product_id": prod.id, "quantity": 1.0}],
        "payment_mode": "UDHAAR"
    })
    bill_id2 = bill_res2.json()["id"]
    sess_res2 = client.post("/api/v1/verification/sessions", json={"bill_id": bill_id2})
    sess2_id = sess_res2.json()["session_id"]

    # Expire session in DB
    db = SessionLocal()
    try:
        vs2 = db.query(VerificationSession).filter(VerificationSession.id == sess2_id).first()
        vs2.expires_at = datetime.utcnow() - timedelta(minutes=10)
        otp2 = vs2.otp_code
        db.commit()
    finally:
        db.close()

    exp_res = client.post("/api/v1/verification/verify", json={
        "session_id": sess2_id,
        "otp": otp2
    })
    assert exp_res.status_code == 400
    assert "expired" in exp_res.json()["detail"].lower()


def test_18_to_20_customer_and_transaction_binding_and_attempt_protection():
    """Points 18-20: Cross-customer and cross-transaction binding; brute force attempt protection."""
    cust_a = _create_verified_customer("Harish Rawat", credit_limit=5000.0)
    cust_b = _create_verified_customer("Inderjit Singh", credit_limit=5000.0)
    prod = _get_or_create_product()

    bill_a = client.post("/api/v1/billing/finalize", json={
        "customer_id": cust_a["id"],
        "items": [{"product_id": prod.id, "quantity": 1.0}],
        "payment_mode": "UDHAAR"
    }).json()

    bill_b = client.post("/api/v1/billing/finalize", json={
        "customer_id": cust_b["id"],
        "items": [{"product_id": prod.id, "quantity": 1.0}],
        "payment_mode": "UDHAAR"
    }).json()

    sess_a = client.post("/api/v1/verification/sessions", json={"bill_id": bill_a["id"]}).json()

    # Point 19: Session for transaction A cannot verify transaction B
    cross_tx_res = client.post("/api/v1/verification/verify", json={
        "session_id": sess_a["session_id"],
        "bill_id": bill_b["id"],
        "otp": "1234"
    })
    assert cross_tx_res.status_code == 400
    assert "does not match bill" in cross_tx_res.json()["detail"].lower()

    # Point 18: OTP for customer A cannot verify customer B
    cross_cust_res = client.post("/api/v1/verification/verify", json={
        "session_id": sess_a["session_id"],
        "customer_id": cust_b["id"],
        "otp": "1234"
    })
    assert cross_cust_res.status_code == 400
    assert "does not belong" in cross_cust_res.json()["detail"].lower()

    # Point 20: Brute force attempt protection locks session after max attempts
    db = SessionLocal()
    try:
        vs = db.query(VerificationSession).filter(VerificationSession.id == sess_a["session_id"]).first()
        vs.attempts = 3
        vs.status = "FAILED"
        db.commit()
    finally:
        db.close()

    locked_res = client.post("/api/v1/verification/verify", json={
        "session_id": sess_a["session_id"],
        "otp": "1234"
    })
    assert locked_res.status_code == 400
    assert "maximum verification attempts exceeded" in locked_res.json()["detail"].lower()


def test_21_to_25_udhaar_finalization_accounting_and_inventory():
    """Points 21-25: Successful OTP updates inventory, balance, ledger atomically; failure leaves them untouched."""
    cust = _create_verified_customer("Jitendra Joshi", credit_limit=2000.0)
    prod = _get_or_create_product("Tata Salt", price=25.0, stock=40.0)

    initial_stock = prod.stock_quantity
    initial_balance = cust["current_udhaar_balance"]

    bill = client.post("/api/v1/billing/finalize", json={
        "customer_id": cust["id"],
        "items": [{"product_id": prod.id, "quantity": 4.0}],
        "payment_mode": "UDHAAR"
    }).json()

    # Point 22: Before verification, stock and balance MUST remain untouched!
    db = SessionLocal()
    try:
        db.expire_all()
        p_check = db.query(Product).filter(Product.id == prod.id).first()
        c_check = db.query(Customer).filter(Customer.id == cust["id"]).first()
        assert p_check.stock_quantity == initial_stock
        assert c_check.current_udhaar_balance == initial_balance
    finally:
        db.close()

    sess = client.post("/api/v1/verification/sessions", json={"bill_id": bill["id"]}).json()
    db = SessionLocal()
    try:
        vs = db.query(VerificationSession).filter(VerificationSession.id == sess["session_id"]).first()
        otp = vs.otp_code
    finally:
        db.close()

    # Point 21, 23, 24: Successful OTP finalizes Udhaar
    verify_res = client.post("/api/v1/verification/verify", json={
        "session_id": sess["session_id"],
        "otp": otp
    })
    assert verify_res.status_code == 200
    assert verify_res.json()["success"] is True

    # Check atomic stock deduction and balance update
    db = SessionLocal()
    try:
        db.expire_all()
        p_after = db.query(Product).filter(Product.id == prod.id).first()
        c_after = db.query(Customer).filter(Customer.id == cust["id"]).first()
        bill_db = db.query(Bill).filter(Bill.id == bill["id"]).first()
        tx = db.query(UdhaarTransaction).filter(UdhaarTransaction.bill_id == bill["id"]).first()

        assert p_after.stock_quantity == initial_stock - 4.0
        assert c_after.current_udhaar_balance == 100.0  # 4 * 25.0
        assert bill_db.status == "COMPLETED"
        assert tx is not None
        assert tx.amount == 100.0
        assert tx.transaction_type == "DEBIT_PURCHASE"
    finally:
        db.close()

    # Point 25: Receipt delivery preparation
    rec_res = client.get(f"/api/v1/receipts/{bill['id']}")
    assert rec_res.status_code == 200
    rec_data = rec_res.json()
    assert rec_data["status"] in ["CUSTOMER_VERIFIED", "COMPLETED"]
    assert rec_data["is_verified"] is True
    assert rec_data["total_amount"] == 100.0


